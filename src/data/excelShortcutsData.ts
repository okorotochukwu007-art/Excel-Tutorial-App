export type ShortcutCategory =
  | 'Formulas & Calculation'
  | 'Navigation & Selection'
  | 'Data & Filtering'
  | 'Formatting & Alignment'
  | 'Editing & Clipboard'
  | 'Auditing & Utilities';

export interface ExcelShortcut {
  id: string;
  name: string;
  action: string;
  category: ShortcutCategory;
  windowsKeys: string[];
  windowsDisplay: string;
  macKeys: string[];
  macDisplay: string;
  normalizedComboWin: string; // e.g. "alt+="
  normalizedComboMac: string; // e.g. "opt+cmd+="
  description: string;
  workplaceProTip: string;
  difficulty: 'Essential' | 'Intermediate' | 'Pro';
}

export interface ShortcutSpeedQuestion {
  id: string;
  prompt: string;
  scenario: string;
  shortcut: ExcelShortcut;
  options: {
    label: string;
    isCorrect: boolean;
  }[];
}

